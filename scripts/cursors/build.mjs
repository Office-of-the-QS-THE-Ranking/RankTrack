// Renders the site cursors to public/cursors as SVG plus 1x and 2x PNG, and writes
// src/styles/cursor-frames.css for the click pulse.
// Run: node scripts/cursors/build.mjs
import { mkdir, writeFile } from "node:fs/promises";
import sharp from "sharp";
import { PULSE, cursors } from "./shapes.mjs";

const out = new URL("../../public/cursors/", import.meta.url);
await mkdir(out, { recursive: true });

for (const [name, { svg }] of Object.entries(cursors)) {
  await writeFile(new URL(`${name}.svg`, out), svg);
  for (const scale of [1, 2]) {
    const file = new URL(`${name}${scale === 1 ? "" : "@2x"}.png`, out);
    await sharp(Buffer.from(svg), { density: 72 * scale }).png().toFile(file.pathname);
  }
}
const value = (fn, name, keyword) =>
  fn === "url"
    ? `url("/cursors/${name}.png") 3 3, ${keyword}`
    : `${fn}(url("/cursors/${name}.png") 1x, url("/cursors/${name}@2x.png") 2x) 3 3, ${keyword}`;
const frames = (fn, pad) =>
  PULSE.map(
    (k) =>
      `${pad}:root[data-cursor="${k}"] {\n` +
      `${pad}  --cursor-default: ${value(fn, `arrow-${k}`, "default")};\n` +
      `${pad}  --cursor-pointer: ${value(fn, `pointer-${k}`, "pointer")};\n` +
      `${pad}  --cursor-gold: ${value(fn, `gold-${k}`, "pointer")};\n` +
      `${pad}}\n`,
  ).join("");
const supports = (fn) => `@supports (cursor: ${fn}(url("/cursors/arrow.png") 1x) 3 3, default) {\n${frames(fn, "  ")}}\n`;
const css =
  `/* Generated by scripts/cursors/build.mjs: click pulse frames, set by CursorFx through data-cursor on <html>. */\n` +
  frames("url", "") + "\n" + supports("-webkit-image-set") + "\n" + supports("image-set");
await writeFile(new URL("../../src/styles/cursor-frames.css", import.meta.url), css);
console.log("Cursors written to public/cursors and src/styles/cursor-frames.css");
