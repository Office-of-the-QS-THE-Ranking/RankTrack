/*
 * Builds the analytics engine's seed from the Office's "UST Dashboard" folder: one methodology pack per edition
 * (checked by the same readPack the Methodology page uses), the template profiles and the unit aliases, then the SQL
 * that upserts them. Rerun it when the folder gains a new methodology or template, and save the SQL as a migration.
 *
 *   npx tsx scripts/analytics/build.ts --drive "$HOME/Downloads/UST Dashboard" \
 *     [--the-text <THE methodology as .txt, or the .pdf with python3 + pypdf>] [--out <folder for the packs' JSON>] > seed.sql
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { nextEdition, readPack } from "../../src/lib/analytics/pack";
import type { MethodologyPack } from "../../src/lib/analytics/types";
import { greenmetric2026 } from "./greenmetric-2026";
import { ALIASES, PROFILES, THE_FEEDS } from "./profiles";
import { qsSubject2026, subjectKey } from "./qs-subject-2026";
import { qsSustainability2027 } from "./qs-sustainability-2027";
import { packsSql } from "./shared";
import { theImpact2026 } from "./the-impact";
import { wuri2026 } from "./wuri-2026";

const arg = (name: string) => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const drive = arg("drive") ?? `${process.env.HOME}/Downloads/UST Dashboard`;
const theText = arg("the-text") ?? join(drive, "2 THE Sustainability/THE.SustainabilityImpactRatings.METHODOLOGY.2026.v2.1.pdf");
const out = arg("out");
const warn = (s: string) => process.stderr.write(`${s}\n`);

const the = theImpact2026(join(drive, "2 THE Sustainability/Submissions/SIMBAHAYAN/UST SIMBAHAYAN Impact 2026-data collection support v1.xlsx"), theText);
the.report.forEach((r) => warn(`THE: ${r}`));
// Template uploads that can suggest THE's figures.
for (const i of the.pack.indicators) {
  const hit = THE_FEEDS.find(([re]) => re.test(i.name));
  if (hit && i.input.type === "number") i.feeds = [{ kind: "template", profile: hit[1], measure: hit[2] }];
}
const the2027 = nextEdition(the.pack, 2027);
the2027.edition = {
  ...the2027.edition,
  label: "THE Impact Ratings 2027",
  period: "Data year 2025 (AY 2024–2025 and AY 2025–2026)",
  status: "Active",
  methodology: "Sustainability Impact Ratings Methodology 2026 v1.1, until THE publishes 2027’s",
  closesOn: "2026-11-20",
  sources: [...the.pack.edition.sources, "SDG Guidelines.docx (memorandum UST: S052-00-ME02)"],
};

const qs = qsSustainability2027(join(drive, "1QS Sustainability/Letter"));
qs.report.forEach((r) => warn(`QS Sustainability: ${r}`));

const packs: MethodologyPack[] = [greenmetric2026(), the.pack, the2027, qs.pack, wuri2026(), qsSubject2026()].map((p) => readPack(JSON.parse(JSON.stringify(p))));
for (const p of packs) warn(`${p.edition.id}: ${p.groups.length} groups, ${p.indicators.length} indicators, ${p.indicators.filter((i) => i.score).length} scored`);

if (out) {
  mkdirSync(out, { recursive: true });
  for (const p of packs) writeFileSync(join(out, `${p.edition.id}.json`), `${JSON.stringify(p, null, 2)}\n`);
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const profileSql = PROFILES.map(
  (p, i) =>
    `  (${q(p.key)}, ${i + 1}, ${q(p.name)}, ${p.owner ? q(p.owner) : "null"}, ${q(p.description)}, $j$${JSON.stringify({ kind: p.kind, headers: p.headers, skip: p.skip ?? [], measures: p.measures, dimensions: p.dimensions, minCell: p.minCell, pairs: p.pairs ?? [] })}$j$::jsonb, 'system', now())`,
).join(",\n");
const aliasSql = Object.entries(ALIASES)
  .map(([alias, unit]) => `  (${q(alias)}, ${q(unit)})`)
  .join(",\n");

process.stdout.write(`-- Generated by scripts/analytics/build.ts from the Office's UST Dashboard folder. Upserts only.\n\n`);
process.stdout.write(packsSql(packs));
process.stdout.write(`\ninsert into public.analytics_profiles (key, position, name, owner_unit, description, spec, updated_by, updated_at) values\n${profileSql}\non conflict (key) do nothing;\n\n`);
process.stdout.write(`insert into public.analytics_aliases (alias, unit_id) values\n${aliasSql}\non conflict (alias) do nothing;\n\n`);
// The one result the fact file states plainly: Medicine, 701–850 in 2026.
process.stdout.write(
  `insert into public.analytics_benchmarks (ranking_slug, year, peer_id, metric, value, label, source, note, entered_by) values\n  ('qs-subject', 2026, '', '${subjectKey("Medicine")}:rank', null, '701-850', 'import', 'QS by Subject 2026 fact file and certificate', 'system')\non conflict (ranking_slug, year, peer_id, metric) do nothing;\n`,
);
